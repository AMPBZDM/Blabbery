/**
 * Selects a random word suggestion from the category or the story's own examples.
 */
export function getRandomWordSuggestion(
  category: WordCategoryType,
  specificExamples?: string[]
): string {
  const pool = [
    ...(specificExamples || []),
    ...(WORD_BANKS[category] || WORD_BANKS.noun),
  ];
  if (pool.length === 0) return 'something';
  const randomIndex = Math.floor(Math.random() * pool.length);
  return pool[randomIndex];
}
